"""Generate docs/supported-rules.md from the rule registry.

Run from the repository root after installing the scanner:
    python scripts/generate_rule_docs.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "packages" / "scanner" / "src"))

from aegisai import __version__  # noqa: E402
from aegisai.engine.registry import default_registry  # noqa: E402

HEADER = """# Supported rules

Generated by `scripts/generate_rule_docs.py` from the rule registry of AegisAI {version}.
Do not edit by hand; run `make rules-doc`.

Severity and confidence are **defaults**: individual findings may be raised or lowered based
on evidence (for example, a validation-looking check lowers confidence and marks the finding
"review required"). Rules marked *heuristic* always require human review.

| ID | Name | Pack | Default severity | Default confidence | Heuristic | Artifacts | CWE |
|----|------|------|------------------|--------------------|-----------|-----------|-----|
"""


def main() -> int:
    registry = default_registry()
    lines = [HEADER.format(version=__version__)]
    for meta in registry.metadata():
        lines.append(
            f"| {meta.rule_id} | {meta.name} | {meta.pack.value} | {meta.default_severity.value} | "
            f"{meta.default_confidence.value} | {'yes' if meta.heuristic else 'no'} | "
            f"{', '.join(a.value for a in meta.artifact_types)} | {', '.join(meta.cwe_ids) or '-'} |"
        )
    lines.append("\n## Rule details\n")
    for meta in registry.metadata():
        lines.append(f"### {meta.rule_id} - {meta.name}\n")
        lines.append(f"*Version {meta.version} | pack `{meta.pack.value}` | category `{meta.category.value}`*\n")
        if meta.requires_integration:
            lines.append(f"Requires integration: `{meta.requires_integration}`.\n")
        lines.append(meta.description + "\n")
        lines.append(f"- **Confidence:** {meta.confidence_behavior}")
        lines.append(f"- **Impact:** {meta.impact}")
        lines.append(f"- **Remediation:** {meta.remediation}")
        if meta.owasp_references:
            lines.append(f"- **OWASP:** {', '.join(meta.owasp_references)}")
        if meta.references:
            lines.append("- **References:**")
            lines.extend(f"  - {ref}" for ref in meta.references)
        lines.append("")
    target = ROOT / "docs" / "supported-rules.md"
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {target} ({len(registry)} rules)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
